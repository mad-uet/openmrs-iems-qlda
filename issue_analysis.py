"""Write the fixed-sample issue analysis for the dashboard, report and slides."""

from bisect import bisect_right
from collections import Counter
import csv
from pathlib import Path
from statistics import median


CATEGORY_LABELS = {
    "bug": "Lỗi",
    "change": "Yêu cầu thay đổi",
    "insufficient": "Không đủ thông tin",
}
HOUR_CUTOFFS = (24, 168, 336)


def classification_counts(source: Path, issue_numbers: set[int]) -> Counter[str]:
    counts: Counter[str] = Counter()
    seen: set[int] = set()
    with source.open(encoding="utf-8", newline="") as stream:
        issues = csv.DictReader(stream)
        if issues.fieldnames != ["number", "category", "reason"]:
            raise ValueError(f"{source.name} must have number, category, reason columns")
        for issue in issues:
            if None in issue or any(value is None for value in issue.values()):
                raise ValueError(f"{source.name}:{issues.line_num}: wrong number of fields")
            number = int(issue["number"])
            category = issue["category"]
            if number not in issue_numbers or number in seen:
                raise ValueError(f"{source.name}: unknown or repeated issue #{number}")
            if category not in CATEGORY_LABELS or not issue["reason"].strip():
                raise ValueError(f"{source.name}: invalid category or missing reason for issue #{number}")
            seen.add(number)
            counts[category] += 1
    if missing := issue_numbers - seen:
        raise ValueError(f"{source.name}: missing classifications for {sorted(missing)}")
    return counts


def write_analysis(out: Path, classifications: Path, issue_hours: dict[int, float | None]) -> None:
    categories = classification_counts(classifications, set(issue_hours))
    hours = [duration for duration in issue_hours.values() if duration is not None]
    closed = len(hours)
    opened = len(issue_hours) - closed
    median_duration_text = f"{median(hours):.1f}".replace(".", ",") + " giờ" if hours else "chưa có"

    buckets = Counter(bisect_right(HOUR_CUTOFFS, duration) for duration in hours)
    lower, middle_cutoff, upper = HOUR_CUTOFFS
    distribution = [
        (f"Dưới {lower}", buckets[0]),
        (f"Từ {lower} đến dưới {middle_cutoff}", buckets[1]),
        (f"Từ {middle_cutoff} đến dưới {upper}", buckets[2]),
        (f"Từ {upper} trở lên", buckets[3]),
    ]
    category_rows = [(label, categories[key]) for key, label in CATEGORY_LABELS.items()]

    tex = [
        "% Generated by build_weekly.py. Edit the source data or script instead.",
        rf"\newcommand{{\IssueTotalCount}}{{{len(issue_hours)}}}",
        rf"\newcommand{{\IssueClosedCount}}{{{closed}}}",
        rf"\newcommand{{\IssueOpenCount}}{{{opened}}}",
        rf"\newcommand{{\IssueMedianDuration}}{{{median_duration_text}}}",
    ]
    for macro, rows in (("IssueDurationRows", distribution), ("IssueCategoryRows", category_rows)):
        tex.append(rf"\newcommand{{\{macro}}}{{%")
        tex.extend(rf"  {label} & {count} \\" for label, count in rows)
        tex.append("}")
    (out / "issue-analysis.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")

    dashboard = [
        "# Project Dashboard",
        "",
        "Kho cấu hình OpenMRS cho Indianapolis EMS có "
        f"**{len(issue_hours)} issue** trong bản cố định. "
        "[Nguồn và bản dữ liệu UTC](../README.md#bản-dữ-liệu-cố-định)",
        "",
        "## Lượt tạo và đóng theo tuần UTC",
        "",
        "[Biểu đồ theo tuần](weekly.pdf) · [Bảng theo tuần](weekly.csv) · "
        "[Đối chiếu theo mã issue](issue-weeks.csv)",
        "",
        "## Thời gian từ mở đến đóng issue",
        "",
        f"**Trung vị {median_duration_text}**. Phép tính dùng {closed} issue đã đóng và bỏ qua {opened} issue còn mở.",
        "Mỗi giá trị là chênh lệch giữa thời điểm đóng và tạo, tính theo giờ.",
        "",
        "| Khoảng thời gian (giờ) | Số issue đã đóng |",
        "| --- | ---: |",
        *(f"| {label} | {count} |" for label, count in distribution),
        "",
        "Khoảng này gồm cả thời gian chờ phản hồi hoặc kiểm thử. Đo giờ công cần nhật ký làm việc. "
        "Số liệu chỉ bao quát issue công khai của kho cấu hình. Dự án còn có công việc ở các kho khác và ngoài GitHub.",
        "",
        "## Phân loại nội dung",
        "",
        "Bảng gồm cả issue còn mở. Phân loại dựa trên mô tả hành vi hoặc yêu cầu trong "
        "tiêu đề, nội dung và thảo luận khi cần. [Mã issue và lý do](../data/issue-classifications.csv)",
        "",
        "| Nhóm | Số issue |",
        "| --- | ---: |",
        *(f"| {label} | {count} |" for label, count in category_rows),
        "",
        "[Cách chạy lại và tự đối chiếu bằng Excel](../README.md#tự-đối-chiếu-bằng-excel)",
        "",
    ]
    (out / "dashboard.md").write_text("\n".join(dashboard), encoding="utf-8")
